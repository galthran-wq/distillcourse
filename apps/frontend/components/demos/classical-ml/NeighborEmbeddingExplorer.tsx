/**
 * NeighborEmbeddingExplorer — precomputed t-SNE maps of one labeled dataset
 * (150 points, 3 classes in 30-D with two high-variance nuisance
 * dimensions) at perplexities 2/5/30/100 beside its PCA projection, plus a
 * pure-noise dataset (150 points, isotropic 100-D Gaussian) at
 * perplexities 2 and 30. Switching views crossfades point positions, so
 * the same point can be followed between maps. Guided task (lesson): find
 * the perplexity where class structure is clearest (the silhouette
 * readout confirms it), then falsify "visible clusters imply structure"
 * on the noise dataset at perplexity 2.
 * Embeddings generated offline with scikit-learn (PCA init, fixed seed);
 * coordinates packed as 0–999 integer pairs.
 * NOTE: course.yaml specs this as "PerplexityExplorer", but the demo
 * registry is a flat namespace and classical-ml-interview already claims
 * that name; the tsne lesson's demo.component must be renamed to
 * NeighborEmbeddingExplorer (human curation change).
 */

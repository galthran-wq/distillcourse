const DATASETS = [
  { label: "three clusters, 30-D", views: CLUSTER_VIEWS, labeled: true },
  { label: "pure noise, 100-D", views: NOISE_VIEWS, labeled: false },
];

export default function NeighborEmbeddingExplorer() {
  // D3: arrive on the labeled data at perplexity 2 — already fragmented.
  const [dataset, setDataset] = useState(0);
  const [viewIdx, setViewIdx] = useState(1);

  const { views, labeled } = DATASETS[dataset];
  const view = views[Math.min(viewIdx, views.length - 1)];

  return (
    <Panel>
      <div className="flex flex-wrap items-baseline gap-x-4">
        <PresetGroup
          labels={DATASETS.map((d) => d.label)}
          activeIndex={dataset}
          onSelect={(i) => {
            setDataset(i);
            setViewIdx(i === 0 ? 1 : 0); // noise opens on perplexity 2 (the task)
          }}
        />
        <PresetGroup
          labels={views.map((v) => v.label)}
          activeIndex={Math.min(viewIdx, views.length - 1)}
          onSelect={setViewIdx}
        />
      </div>
      <Readout>
        {labeled && view.sil !== undefined && (
          <>
            class silhouette in the map: <strong>{view.sil.toFixed(2)}</strong> —{" "}
          </>
        )}
        {view.note}
      </Readout>
      <svg
        viewBox={`0 0 ${W} ${W}`}
        className="mx-auto mt-2 block w-full max-w-90 select-none"
        role="img"
        aria-label={`${DATASETS[dataset].label}, ${view.label}: ${view.note}`}
      >
        <rect x="0" y="0" width={W} height={W} rx="4" fill="currentColor" opacity="0.04" />
        {view.pts.map(([x, y], i) => (
          <circle
            // Keyed per dataset: within one dataset the circles persist and
            // their transforms transition, so a clump can be watched
            // dispersing; across datasets there is no correspondence, so
            // remount without motion.
            key={`${dataset}-${i}`}
            cx="0"
            cy="0"
            r="3.2"
            className="transition-transform duration-(--motion-base)"
            style={{ transform: `translate(${x}px, ${y}px)` }}
            fill={labeled ? CLASS_COLORS[Math.floor(i / 50)] : "currentColor"}
            opacity={labeled ? 0.85 : 0.55}
          />
        ))}
        <text x="10" y="20" fontSize="11" fill="currentColor" opacity="0.65">
          {view.label} — axes carry no meaning
        </text>
        {labeled ? (
          CLASS_COLORS.map((c, i) => (
            <g key={c}>
              <circle cx={14 + 74 * i} cy={W - 16} r="4" fill={c} />
              <text x={24 + 74 * i} y={W - 12} fontSize="11" fill="currentColor" opacity="0.65">
                class {"ABC"[i]}
              </text>
            </g>
          ))
        ) : (
          <text x="10" y={W - 12} fontSize="11" fill="currentColor" opacity="0.65">
            no labels — isotropic Gaussian noise
          </text>
        )}
      </svg>
    </Panel>
  );
}

const CLASS_COLORS = ["#e2903a", "#4c8dd6", "#5aa46a"];
const W = 340, PAD = 18, SPAN = W - 2 * PAD;

function decode(s: string): [number, number][] {
  const v = s.split(",").map(Number);
  const pts: [number, number][] = [];
  for (let i = 0; i < v.length; i += 2)
    pts.push([PAD + (v[i] / 999) * SPAN, PAD + (v[i + 1] / 999) * SPAN]);
  return pts;
}

interface View {
  label: string;
  note: string;
  sil?: number; // silhouette of the true classes in this map (labeled data only)
  pts: [number, number][];
}

